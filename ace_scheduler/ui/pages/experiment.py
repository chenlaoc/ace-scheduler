from PySide6.QtWidgets import QGridLayout, QHBoxLayout, QPushButton, QComboBox, QSpinBox, QPlainTextEdit, QLineEdit, QCheckBox

from ..components import GlassCard, label
from ..history_chart import HistoryChart
from .base import Page


class ExperimentPage(Page):
    def __init__(self, owner):
        super().__init__()
        intro = GlassCard()
        intro.body.addWidget(label("可复查的实验会话", "sectionTitle"))
        intro.body.addWidget(label("开始采集基线后，到调度策略页手动应用。直接应用也会新建会话，保留此前最多 60 秒。恢复不会覆盖旧实验。", "muted", True))
        selection = QHBoxLayout()
        self.filter = QComboBox()
        for title, value in (("全部记录", "all"), ("运行中实例", "running"), ("已结束实例", "ended"), ("实验会话", "sessions")):
            self.filter.addItem(title, value)
        self.filter.currentIndexChanged.connect(owner.refresh_experiment)
        self.picker = QComboBox()
        self.picker.setMinimumWidth(220)
        self.picker.currentIndexChanged.connect(owner.select_experiment)
        selection.addWidget(self.filter)
        selection.addWidget(self.picker, 1)
        self.open_button = QPushButton("打开 JSON…")
        self.open_button.clicked.connect(owner.open_experiment)
        selection.addWidget(self.open_button)
        intro.body.addLayout(selection)
        steps = QHBoxLayout()
        self.baseline, self.transition, self.after = QSpinBox(), QSpinBox(), QSpinBox()
        for text, control, low, default in (("基线", self.baseline, 1, 60), ("过渡", self.transition, 0, 3), ("实验段", self.after, 1, 60)):
            steps.addWidget(label(text, "muted"))
            control.setRange(low, 600)
            control.setValue(default)
            control.setSuffix(" 秒")
            steps.addWidget(control)
        self.begin_button = QPushButton("开始基线")
        self.begin_button.clicked.connect(owner.begin_experiment)
        self.finish_button = QPushButton("结束记录")
        self.finish_button.clicked.connect(owner.finish_experiment)
        steps.addWidget(self.begin_button)
        steps.addWidget(self.finish_button)
        intro.body.addLayout(steps)
        intro.body.addWidget(label("会话保存在本次运行内；退出前保存 JSON，可在下次打开。最多保留 64 个会话，不会自动删除旧实验。", "muted", True))
        self.repeated_button = QPushButton("多轮实验汇总…")
        self.repeated_button.clicked.connect(owner.show_repeated_experiments)
        intro.body.addWidget(self.repeated_button)
        self.body.addWidget(intro)

        scene = GlassCard("场景与时间标记")
        scene_row = QHBoxLayout()
        self.scene_name = QLineEdit()
        self.scene_name.setPlaceholderText("场景名称，如：训练场固定路线")
        self.scene_name.setMaxLength(200)
        self.scene_save = QPushButton("保存场景信息")
        self.scene_save.clicked.connect(owner.save_scene)
        scene_row.addWidget(self.scene_name, 1)
        scene_row.addWidget(self.scene_save)
        scene.body.addLayout(scene_row)
        self.scene_notes = QPlainTextEdit()
        self.scene_notes.setPlaceholderText("备注：游戏版本、画质、限帧、缓存状态和后台活动（最多 4000 字）")
        self.scene_notes.setMaximumHeight(65)
        scene.body.addWidget(self.scene_notes)
        markers = QHBoxLayout()
        self.marker = QComboBox()
        self.marker.setEditable(True)
        self.marker.addItems(["进入游戏", "加载开始", "加载结束", "对局开始", "卡顿", "对局结束"])
        self.marker.lineEdit().setMaxLength(200)
        self.marker_button = QPushButton("记录时间标记")
        self.marker_button.clicked.connect(owner.mark_scene)
        markers.addWidget(self.marker, 1)
        markers.addWidget(self.marker_button)
        scene.body.addLayout(markers)
        self.clock_status = label("场景标记只记录时间，不应用调度策略。", "muted", True)
        scene.body.addWidget(self.clock_status)
        self.body.addWidget(scene)

        disks = GlassCard("物理磁盘 · 可选采集")
        disk_row = QHBoxLayout()
        self.disk_enabled = QCheckBox("启用磁盘记录")
        self.disk_enabled.toggled.connect(owner.toggle_disk_capture)
        self.disk_picker = QComboBox()
        self.disk_picker.setMinimumWidth(220)
        self.disk_picker.currentIndexChanged.connect(owner.select_disk)
        disk_row.addWidget(self.disk_enabled)
        disk_row.addWidget(self.disk_picker, 1)
        disks.body.addLayout(disk_row)
        self.disk_status = label("默认关闭。启用后选择设备，再开始基线；同一次采集可供多个会话引用。", "muted", True)
        disks.body.addWidget(self.disk_status)
        self.disk_details = QPlainTextEdit()
        self.disk_details.setReadOnly(True)
        self.disk_details.setMinimumHeight(125)
        self.disk_details.setMaximumHeight(180)
        disks.body.addWidget(self.disk_details)
        disks.body.addWidget(label("设备总体负载不属于单个进程。延迟按请求数加权；无请求时留空。当前队列为瞬时值。", "muted", True))
        self.body.addWidget(disks)
        self.editing_session = None

        frames = GlassCard("外部帧时间 · 离线分析")
        self.frame_import = QPushButton("导入 PresentMon CSV…")
        self.frame_import.clicked.connect(owner.import_frames)
        frames.body.addWidget(self.frame_import)
        self.frame_details = QPlainTextEdit()
        self.frame_details.setReadOnly(True)
        self.frame_details.setMinimumHeight(180)
        self.frame_details.setMaximumHeight(280)
        frames.body.addWidget(self.frame_details)
        frames.body.addWidget(label("导入会创建只读分析副本。原会话保留；低覆盖、日志丢失和近似对齐会明确标注。", "muted", True))
        self.body.addWidget(frames)
        self.frame_session_id = None

        history = GlassCard()
        row = QHBoxLayout()
        owner.history_title = label("等待选择进程", "sectionTitle", True)
        row.addWidget(owner.history_title, 1)
        owner.export_button = QPushButton("导出 CSV")
        owner.export_button.clicked.connect(owner.export_csv)
        owner.export_button.setEnabled(False)
        row.addWidget(owner.export_button)
        self.save_button = QPushButton("保存 JSON")
        self.save_button.clicked.connect(owner.save_experiment)
        row.addWidget(self.save_button)
        self.remove_button = QPushButton("移除记录")
        self.remove_button.clicked.connect(owner.remove_experiment)
        row.addWidget(self.remove_button)
        history.body.addLayout(row)
        self.chart = HistoryChart()
        self.chart.setMinimumHeight(215)
        history.body.addWidget(self.chart)
        history.body.addWidget(label("会话曲线使用固定窗口；虚线标记应用开始，过渡期不计入前后对照。", "muted", True))
        self.body.addWidget(history)

        comparison = GlassCard("前后对照")
        grid = QGridLayout()
        grid.setHorizontalSpacing(30)
        grid.setVerticalSpacing(18)
        grid.addWidget(label("指标", "muted"), 0, 0)
        grid.addWidget(label("应用前 · Before", "detailValue"), 0, 1)
        grid.addWidget(label("应用后 · After", "detailValue"), 0, 2)
        self.values = {}
        for row, (field, name) in enumerate((("cpu_percent", "CPU %"), ("read_mbps", "Read MB/s"), ("write_mbps", "Write MB/s")), 1):
            grid.addWidget(label(name, "body"), row, 0)
            for column, phase in ((1, "before"), (2, "after")):
                value = label("—", "body", True)
                grid.addWidget(value, row, column)
                self.values[(field, phase)] = value
        grid.setColumnStretch(1, 1)
        grid.setColumnStretch(2, 1)
        comparison.body.addLayout(grid)
        owner.comparison = label("还没有应用策略。先观察一段时间，应用后即可查看前后对照。", "muted", True)
        comparison.body.addWidget(owner.comparison)
        self.body.addWidget(comparison)
        events = GlassCard("策略与操作事件")
        self.events = QPlainTextEdit()
        self.events.setReadOnly(True)
        self.events.setMinimumHeight(140)
        self.events.setMaximumHeight(210)
        events.body.addWidget(self.events)
        self.body.addWidget(events)
        self.body.addWidget(label("请在相近场景下比较，并确认操作已成功。CPU 调度不会直接限制磁盘读写速度。", "muted", True))
        self.body.addStretch()
